/* Critical CSS: inlines the rules the first paint needs and keeps them honest.
   The block is computed from the live stylesheets in a browser, not copied by
   hand, so it can be re-run whenever CSS or markup changes. Run with --write to
   update index.html, --check to fail on drift (CI). */
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const { start } = require('./serve.cjs');

const PORT = Number(process.env.CRITICAL_PORT || 8790);
const ROOT = path.resolve(__dirname, '..');
const INDEX = path.join(ROOT, 'index.html');
const START = '/* critical-css:start generated by scripts/critical-css.cjs */';
const END = '/* critical-css:end */';
const VIEWPORTS = [{ width: 390, height: 844 }, { width: 1280, height: 900 }];
// Selectors inlined even though nothing matching them sits in the fold: the a11y
// helpers, and media guards, because the fallback panels live below the fold and an
// unconstrained intrinsic width makes mobile browsers zoom out on first paint.
const FORCE = ['[hidden]', '.sr-only', 'img'];

const COLLECT = ({ fold, force }) => {
  const pseudoElement = /::?(?:before|after|first-line|first-letter|selection|marker|placeholder|backdrop)(?:\([^)]*\))?$/i;
  const parts = selector => selector.split(/,(?![^(]*\))/).map(part => part.trim()).filter(Boolean);
  const foldElements = [...document.querySelectorAll('*')].filter(node => {
    const box = node.getBoundingClientRect();
    // A zero-width or zero-height box is still painted (an SVG line), but display:none is both.
    return (box.width > 0 || box.height > 0) && box.top < fold;
  });
  foldElements.push(document.documentElement, document.body);
  const hits = selector => parts(selector).some(part => {
    for (const candidate of [part, part.replace(pseudoElement, '')]) {
      if (!candidate) continue;
      if (force.some(forced => candidate === forced)) return true;
      try { if (foldElements.some(node => node.matches(candidate))) return true; } catch { /* unsupported syntax */ }
    }
    return false;
  });
  const walk = rules => [...rules].map(rule => {
    // CSSStyleRule also carries cssRules for nesting, so dispatch on type first.
    if (rule instanceof CSSStyleRule) {
      return { selector: rule.selectorText, text: rule.cssText, lossy: /:\s*;/.test(rule.cssText), hit: hits(rule.selectorText) };
    }
    if (rule instanceof CSSKeyframesRule) return { keyframes: rule.cssText };
    if (rule instanceof CSSMediaRule) return { media: rule.conditionText, kids: walk(rule.cssRules) };
    if (rule.cssRules) return { media: '', kids: walk(rule.cssRules) };
    return { text: rule.cssText, hit: false };
  });
  const sheets = [];
  const seen = new Set();
  for (const sheet of document.styleSheets) {
    if (!sheet.href) continue;
    const name = new URL(sheet.href).pathname.split('/').pop();
    if (seen.has(name)) continue;
    seen.add(name);
    sheets.push({ name, rules: walk(sheet.cssRules) });
  }
  return sheets;
};

/* Chrome drops a var() shorthand to empty longhands as soon as one of its own longhands is
   declared next to it (background:linear-gradient(var(--ice)) plus background-clip:text), so the
   authored text is recovered from the sheet itself. Keyframes and at-rule preludes are skipped. */
function bodiesBySelector(file) {
  const text = fs.readFileSync(file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  const map = new Map();
  const stack = [];
  let buffer = '';
  for (const char of text) {
    if (char === '{') { stack.push(buffer.trim()); buffer = ''; continue; }
    if (char === '}') {
      const prelude = stack.pop() || '';
      buffer = buffer.trim();
      if (buffer && !prelude.startsWith('@') && !prelude.endsWith('%')) {
        const key = prelude.replace(/\s+/g, ' ');
        map.set(key, [...(map.get(key) || []), buffer]);
      }
      buffer = '';
      continue;
    }
    buffer += char;
  }
  return map;
}

function repair(rules, map) {
  return rules.map(rule => {
    if (rule.kids) return { ...rule, kids: repair(rule.kids, map) };
    if (!rule.lossy) return rule;
    const names = [...rule.text.matchAll(/([a-z-]+):/g)].map(match => match[1]);
    let best = '';
    let score = 0;
    for (const body of map.get(rule.selector.replace(/\s+/g, ' ')) || []) {
      const flat = body.replace(/\s+/g, '');
      const hits = names.filter(name => {
        const words = name.split('-');
        for (let length = words.length; length >= 1; length--) {
          if (flat.includes(`${words.slice(0, length).join('-')}:`)) return true;
        }
        return false;
      }).length;
      if (hits > score) { score = hits; best = body; }
    }
    if (!score) return rule;
    return { ...rule, text: `${rule.selector} { ${best.replace(/\s+/g, ' ')}; }`, lossy: false };
  });
}

const lossy = rules => rules.flatMap(rule => rule.kids ? lossy(rule.kids) : rule.lossy ? [rule.selector] : []);

function merge(a, b) {
  if (!a) return b && { ...b, hit: false, kids: b.kids && b.kids.map(kid => ({ ...kid, hit: false })) };
  if (!b) return a && { ...a, hit: false, kids: a.kids && a.kids.map(kid => ({ ...kid, hit: false })) };
  if (a.keyframes) return a;
  if (a.media !== undefined && b.media !== undefined) {
    const kids = [];
    const length = Math.max(a.kids.length, b.kids.length);
    for (let index = 0; index < length; index++) kids.push(merge(a.kids[index], b.kids[index]));
    return { media: a.media, kids };
  }
  return { ...a, text: a.text, hit: Boolean(a.hit || b.hit) };
}

function emit(rules, pad) {
  const out = [];
  for (const rule of rules) {
    if (!rule) continue;
    if (rule.keyframes) { out.push(pad + rule.keyframes); continue; }
    if (rule.kids) {
      const inner = emit(rule.kids.filter(Boolean), `${pad}  `);
      if (inner.length) out.push(rule.media ? `${pad}@media ${rule.media} {\n${inner.join('\n')}\n${pad}}` : inner.join('\n'));
      continue;
    }
    if (rule.hit) out.push(pad + rule.text);
  }
  return out;
}

(async () => {
  const mode = process.argv[2];
  if (!['--write', '--check'].includes(mode)) {
    console.error('usage: node scripts/critical-css.cjs --write | --check');
    process.exit(2);
  }
  const server = await start(PORT);
  const browser = await chromium.launch();
  const context = await browser.newContext({ javaScriptEnabled: false, viewport: VIEWPORTS[0] });
  const page = await context.newPage();
  try {
    await page.goto(`http://127.0.0.1:${PORT}/`, { waitUntil: 'load' });
    let sheets;
    for (const [index, viewport] of VIEWPORTS.entries()) {
      await page.setViewportSize(viewport);
      await page.waitForTimeout(120);
      const run = await page.evaluate(COLLECT, { fold: viewport.height, force: FORCE });
      const fixed = run.map(sheet => ({ ...sheet, rules: repair(sheet.rules, bodiesBySelector(path.join(ROOT, 'assets', sheet.name))) }));
      const left = fixed.flatMap(sheet => lossy(sheet.rules));
      if (left.length) throw new Error(`unrecoverable lossy rules: ${left.join(', ')}`);
      sheets = sheets ? sheets.map((sheet, position) => ({ name: sheet.name, rules: sheet.rules.map((rule, index2) => merge(rule, fixed[position].rules[index2])) })) : fixed;
    }
    const css = sheets.map(sheet => `/* ${sheet.name} */\n${emit(sheet.rules, '').join('\n')}`).join('\n\n') + '\n';
    const block = `${START}\n${css}${END}`;
    const html = fs.readFileSync(INDEX, 'utf8');
    const current = html.match(/\/\* critical-css:start[\s\S]*?\*\/([\s\S]*?)<\/style>/);
    if (!current) throw new Error('index.html has no <style id="critical-css"> block with the generated markers');
    if (mode === '--check') {
      const ok = current[1].trim() === `${css}${END}`.trim();
      console.log(JSON.stringify({ ok, bytes: Buffer.byteLength(css), rules: css.split('\n').length, drift: ok ? null : 'critical layer is stale; run npm run critical' }));
      if (!ok) process.exitCode = 1;
      return;
    }
    const next = html.replace(new RegExp(`${escape(START)}[\\s\\S]*?${escape(END)}`), block);
    if (next === html && css.length === 0) throw new Error('critical layer is empty');
    fs.writeFileSync(INDEX, next);
    console.log(JSON.stringify({ written: true, bytes: Buffer.byteLength(css), lines: css.split('\n').length }));
  } finally {
    await browser.close();
    await new Promise(resolve => server.close(resolve));
  }
})().catch(error => { console.error(error); process.exit(1); });

function escape(text) { return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }
